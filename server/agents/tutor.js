/* Tutor agent — builds the lesson.
   Library topics are instant and offline; any other topic is generated by the LLM using shared memory.
   Publishes the lesson into shared state so the mentor and quiz agents can use it. */
const { lessonPrompt, validateLesson } = require('../lib/lesson');

const SECTION_OF = { story: 'story', diagram: 'diagram', visual: 'diagram', steps: 'steps', activity: 'activity', hands: 'activity' };

module.exports = {
  name: 'tutor',
  description: 'Builds a personalised lesson from the library or the LLM, adapted with what memory says helps this learner.',

  async handle(input, ctx) {
    const p = input.profile || (await ctx.memory.state()).profile || {};
    const topic = input.topic || p.topic;
    if (!topic) throw Object.assign(new Error('topic is required'), { status: 400 });
    const mem = await ctx.memory.context();
    const { KB, matchTopic } = ctx.kb;

    let lesson = (input.topicId && KB.find(k => k.id === input.topicId)) || matchTopic(topic);
    let source = 'library';
    if (!lesson) {
      if (!ctx.llm.available()) throw Object.assign(new Error(`"${topic}" isn't in the offline library. Add a free AI key in .env to generate any topic.`), { status: 422 });
      const { data, provider } = await ctx.llm.json({
        system: 'You are an expert, warm tutor who writes personalised lessons.',
        prompt: lessonPrompt(topic, p, mem.text), maxTokens: 4000, timeout: 90000
      });
      lesson = validateLesson(data, topic);
      source = 'ai:' + provider;
    }

    // adaptations from long-term memory
    const extraSections = [], notes = [];
    const m = mem.model;
    if (m) {
      const helped = mem.top(m.styles.helped, 2).map(s => SECTION_OF[s]).filter(Boolean);
      helped.forEach(s => { if (s !== SECTION_OF[p.style] && !extraSections.includes(s)) extraSections.push(s); });
      if (helped.length) notes.push('Added the explanation style that helped you before.');
      if (Object.keys(m.struggles).length) { extraSections.push('deep'); }
      if (m.engagement.bored >= 2) { extraSections.push('hook', 'challenge'); notes.push('You\'ve been bored before, so there\'s a hook and a challenge.'); }
    }

    await ctx.memory.setState({ currentLesson: lesson, lessonSource: source });
    await ctx.memory.record('lesson.built', { topic: lesson.title, source, extraSections });
    return { lesson, source, adaptations: { extraSections: [...new Set(extraSections)], notes } };
  }
};
